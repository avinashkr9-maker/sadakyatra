-- One row of settings that apply to every booking.
create table if not exists public.pricing_settings (
  id integer primary key default 1 check (id = 1),
  toll_per_km double precision not null default 1.5,
  gst_percent double precision not null default 5,
  commission_percent double precision not null default 15,
  updated_at timestamptz not null default now()
);
insert into public.pricing_settings (id) values (1) on conflict (id) do nothing;

-- Fixed all-inclusive prices for popular routes, matched when both pins are near the route's ends.
create table if not exists public.fixed_routes (
  id bigint generated by default as identity primary key,
  origin_name text not null,
  origin_lat double precision not null,
  origin_lng double precision not null,
  dest_name text not null,
  dest_lat double precision not null,
  dest_lng double precision not null,
  radius_km double precision not null default 10,
  category text not null references public.vehicle_categories(key),
  one_way_fare double precision not null,
  round_trip_fare double precision,
  active boolean not null default true,
  created_at timestamptz not null default now()
);

-- Vehicle types now come from vehicle_categories instead of a fixed list.
alter table public.partner_applications drop constraint if exists partner_applications_vehicle_category_check;
alter table public.vehicles drop constraint if exists vehicles_category_check;
alter table public.partner_applications drop constraint if exists partner_applications_vehicle_category_fkey;
alter table public.partner_applications add constraint partner_applications_vehicle_category_fkey
  foreign key (vehicle_category) references public.vehicle_categories(key);
alter table public.vehicles drop constraint if exists vehicles_category_fkey;
alter table public.vehicles add constraint vehicles_category_fkey foreign key (category) references public.vehicle_categories(key);

-- Round trips and the driver's share are stored on each booking at the price it was booked at.
alter table public.bookings add column if not exists trip_type text not null default 'ONE_WAY';
alter table public.bookings drop constraint if exists bookings_trip_type_check;
alter table public.bookings add constraint bookings_trip_type_check check (trip_type in ('ONE_WAY','ROUND_TRIP','LOCAL'));
alter table public.bookings add column if not exists return_datetime timestamptz;
alter table public.bookings add column if not exists trip_days integer not null default 1;
alter table public.bookings add column if not exists driver_payout double precision;
alter table public.bookings add column if not exists commission_percent double precision;
alter table public.bookings add column if not exists fixed_route_id bigint references public.fixed_routes(id) on delete set null;
