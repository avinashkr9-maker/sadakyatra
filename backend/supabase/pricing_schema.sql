-- Prices managed from the Admin screen. Run after dispatch_schema.sql. Safe to re-run;
-- seed rows are inserted only when missing, so admin edits are never overwritten.

-- One row per vehicle type. Round trips use their own rate and a minimum km per day.
create table if not exists public.vehicle_categories (
  key text primary key check (key ~ '^[a-z0-9_]{2,30}$'),
  name text not null,
  seats_label text not null default '',
  models text not null default '',
  sort_order integer not null default 100,
  active boolean not null default true,
  base_fare double precision not null default 0,
  per_km double precision not null,
  min_fare double precision not null default 0,
  local_fare double precision not null default 0,
  rt_per_km double precision not null,
  rt_min_km_per_day double precision not null default 250,
  driver_allowance double precision not null default 300,
  updated_at timestamptz not null default now()
);

