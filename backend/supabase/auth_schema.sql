-- OTP login, sessions and roles. Run after bookings_schema.sql. Safe to re-run.
-- Backend-only tables: RLS on with no policies, so the public anon key cannot touch them.

alter table public.users add column if not exists email text;

-- A user can hold several roles (e.g. a vehicle owner who also drives).
-- permissions only matters for 'admin': any of 'bookings', 'partners', 'pricing'.
create table if not exists public.user_roles (
  user_id bigint not null references public.users(id) on delete cascade,
  role text not null check (role in ('customer','driver','vehicle_owner','admin','owner')),
  permissions text[] not null default '{}',
  created_at timestamptz not null default now(),
  primary key (user_id, role)
);

create table if not exists public.otp_codes (
  phone text primary key,
  code_hash text not null,
  expires_at timestamptz not null,
  attempts integer not null default 0,
  sent_in_window integer not null default 1,
  window_started_at timestamptz not null default now(),
  last_sent_at timestamptz not null default now()
);

create table if not exists public.sessions (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.users(id) on delete cascade,
  token_hash text not null unique,
  created_at timestamptz not null default now(),
  expires_at timestamptz not null
);
create index if not exists sessions_user_idx on public.sessions(user_id);

-- Partners now sign up from their own logged-in account.
alter table public.partner_applications add column if not exists applicant_user_id bigint references public.users(id);
alter table public.partner_applications add column if not exists partner_type text not null default 'driver';
alter table public.partner_applications drop constraint if exists partner_applications_partner_type_check;
alter table public.partner_applications add constraint partner_applications_partner_type_check check (partner_type in ('driver','vehicle_owner'));
create index if not exists partner_applications_applicant_idx on public.partner_applications(applicant_user_id);

alter table public.partners add column if not exists user_id bigint references public.users(id);
alter table public.partners add column if not exists partner_type text not null default 'driver';

-- Drivers log in with OTP; the old pasted access token is no longer required.
alter table public.drivers add column if not exists user_id bigint unique references public.users(id);
alter table public.drivers alter column access_token_hash drop not null;

alter table public.user_roles enable row level security;
alter table public.otp_codes enable row level security;
alter table public.sessions enable row level security;
