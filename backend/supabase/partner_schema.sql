create table if not exists public.admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade,
  full_name text,
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create or replace function public.is_sadakyatra_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.admin_users
    where user_id = auth.uid() and active = true
  );
$$;

create table if not exists public.partner_applications (
  id bigint generated by default as identity primary key,
  application_ref text not null unique,
  full_name text not null,
  phone text not null,
  vehicle_number text not null,
  vehicle_category text not null check (vehicle_category in ('sedan','suv','traveller')),
  vehicle_model text not null,
  seats integer,
  driver_name text not null,
  driver_phone text not null,
  city text not null,
  operating_area text not null,
  phone_verified boolean not null default false,
  rc_document_key text,
  dl_document_key text,
  insurance_document_key text,
  status text not null default 'PENDING' check (status in ('PENDING','APPROVED','REJECTED')),
  review_note text,
