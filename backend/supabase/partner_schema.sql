  create or replace function public.approve_partner_application(
    p_application_id bigint,
    p_partner_ref text,
    p_driver_token_hash text,
    p_rc_document_key text,
    p_dl_document_key text,
    p_insurance_document_key text
  )
  returns jsonb
  language plpgsql
  security definer
  set search_path = public
  as $$
  declare
    application public.partner_applications%rowtype;
    new_partner_id bigint;
    new_driver_id bigint;
    new_vehicle_id bigint;
    new_cab_ref text;
  begin
    select * into application
    from public.partner_applications
    where id = p_application_id and status = 'PENDING'
    for update;
    if not found then raise exception 'Only pending applications can be approved'; end if;

    insert into public.partners (partner_ref, application_id, full_name, phone, city, operating_area)
    values (p_partner_ref, application.id, application.full_name, application.phone, application.city, application.operating_area)
    returning id into new_partner_id;

    insert into public.drivers (partner_id, driver_name, phone, access_token_hash)
    values (new_partner_id, application.driver_name, application.driver_phone, p_driver_token_hash)
    returning id into new_driver_id;

    new_vehicle_id := nextval(pg_get_serial_sequence('public.vehicles', 'id'));
    new_cab_ref := 'SY-CAB-' || lpad(new_vehicle_id::text, 6, '0');
    insert into public.vehicles (
      id, cab_ref, plate_no, category, model, seats, partner_id, driver_id,
      rc_document_key, dl_document_key, insurance_document_key
    ) values (
      new_vehicle_id, new_cab_ref, application.vehicle_number, application.vehicle_category, application.vehicle_model,
      application.seats, new_partner_id, new_driver_id,
      p_rc_document_key, p_dl_document_key, p_insurance_document_key
    ) returning id into new_vehicle_id;

    new_cab_ref := 'SY-CAB-' || lpad(new_vehicle_id::text, 6, '0');
    update public.vehicles set cab_ref = new_cab_ref where id = new_vehicle_id;
    update public.partner_applications
    set status = 'APPROVED', phone_verified = true,
        rc_document_key = p_rc_document_key,
        dl_document_key = p_dl_document_key,
        insurance_document_key = p_insurance_document_key,
        reviewed_at = now()
    where id = application.id;

    return jsonb_build_object('partnerId', new_partner_id, 'driverId', new_driver_id,
      'vehicleId', new_vehicle_id, 'cabRef', new_cab_ref);
  end;
  $$;

  -- Functions are executable by PUBLIC by default; restrict this one to the backend.
  revoke execute on function public.approve_partner_application(bigint, text, text, text, text, text) from public, anon, authenticated;
  grant execute on function public.approve_partner_application(bigint, text, text, text, text, text) to service_role;
