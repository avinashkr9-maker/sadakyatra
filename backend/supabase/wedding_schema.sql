-- Wedding & baraat cars, multi-car wedding bookings, and storage for car photos.
-- Run after pricing_schema.sql. Safe to re-run.

create table if not exists public.wedding_vehicles (
  id bigint generated by default as identity primary key,
  name text not null,
  category text not null references public.vehicle_categories(key),
  image_url text,
  price double precision not null,          -- package price per car, all-inclusive (GST inside)
  included_km double precision not null default 100,
  included_hours double precision not null default 8,
  fuel_policy text not null default 'Fuel included for the package km',
  extra_km_rate double precision not null default 0,
  extra_hour_rate double precision not null default 0,
  decoration_options text not null default '',  -- comma separated, e.g. "Flowers, Ribbons & flowers"
  sort_order integer not null default 100,
  active boolean not null default true,
  created_at timestamptz not null default now()
);

insert into public.wedding_vehicles (name, category, price, included_km, included_hours, fuel_policy, extra_km_rate, extra_hour_rate, decoration_options, sort_order)
select * from (values
  ('Maruti Suzuki Dzire', 'sedan', 4500, 100, 8, 'Fuel included for 100 km', 18, 200, 'Simple flowers, Full floral decoration', 10),
  ('Honda City', 'sedan', 6000, 100, 8, 'Fuel included for 100 km', 20, 250, 'Simple flowers, Full floral decoration', 20),
  ('Hyundai Verna', 'sedan', 7000, 100, 8, 'Fuel included for 100 km', 22, 300, 'Simple flowers, Full floral decoration', 30),
  ('Toyota Innova Crysta', 'seven_seater', 9000, 100, 8, 'Fuel included for 100 km', 28, 350, 'Simple flowers, Full floral decoration', 40)
) as seed(name, category, price, included_km, included_hours, fuel_policy, extra_km_rate, extra_hour_rate, decoration_options, sort_order)
where not exists (select 1 from public.wedding_vehicles);

-- A wedding request for several cars becomes one booking per car, linked by group_ref.
alter table public.bookings add column if not exists wedding_vehicle_id bigint references public.wedding_vehicles(id) on delete set null;
alter table public.bookings add column if not exists group_ref text;
alter table public.bookings add column if not exists group_index integer;
alter table public.bookings add column if not exists group_size integer;
alter table public.bookings add column if not exists decoration text;
create index if not exists bookings_group_idx on public.bookings(group_ref);
alter table public.bookings drop constraint if exists bookings_trip_type_check;
alter table public.bookings add constraint bookings_trip_type_check check (trip_type in ('ONE_WAY','ROUND_TRIP','LOCAL','WEDDING'));

alter table public.wedding_vehicles enable row level security;

-- Public bucket for wedding car photos shown in the app (partner documents stay in the private bucket).
insert into storage.buckets (id, name, public)
values ('wedding-cars', 'wedding-cars', true)
on conflict (id) do nothing;
